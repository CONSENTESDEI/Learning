"""
特点：
    1. 存的是键值对 (key : value) 可根据 key 找 value
    2. key 不可重复，可修改
    3. value 可重复，可修改

定义：
    字典名称 = {key1: value1, key2: value2, ...}
    空字典 字典名称 = {}
          字典名称 = dict()

基础操作：
    添加  |   dict[key] = value   |   在字典中添加键值对

    删除  |   pop(key)            |   删除指定的 key 返回对应的 value
         |   del dict[key]       |   删除指定键值对

    修改  |   dict[key] = value   |   修改指定 key 对应的 value

    查询  |   dict[key]           |   根据 key 获取 value
         |   dict.get(key)       |   根据 key 获取 value
         |   dict.values()       |   获取所有 value
         |   dict.keys()         |   获取所有 key
         |   dict.items()        |   获取所有键值对
"""
















